CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Tabel KELAS
CREATE TABLE IF NOT EXISTS public.kelas (
  id TEXT PRIMARY KEY,
  tingkat TEXT NOT NULL,
  jurusan TEXT NOT NULL,
  nama_kelas TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabel SISWA
CREATE TABLE IF NOT EXISTS public.siswa (
  id TEXT PRIMARY KEY,
  nama TEXT NOT NULL,
  kelas TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Aktif',
  tanggal_dibuat DATE DEFAULT CURRENT_DATE,
  no_wa_orang_tua TEXT DEFAULT '',
  qr_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabel PETUGAS_OSIS
CREATE TABLE IF NOT EXISTS public.petugas_osis (
  id TEXT PRIMARY KEY,
  nama TEXT NOT NULL,
  kode TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Aktif',
  tanggal_dibuat DATE DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabel ADMIN
CREATE TABLE IF NOT EXISTS public.admin (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabel ABSENSI
CREATE TABLE IF NOT EXISTS public.absensi (
  id TEXT PRIMARY KEY,
  tanggal DATE NOT NULL,
  jam_datang TEXT NOT NULL,
  id_siswa TEXT NOT NULL,
  nama_siswa TEXT NOT NULL,
  kelas TEXT NOT NULL,
  id_petugas TEXT NOT NULL,
  nama_petugas TEXT NOT NULL,
  status_seragam TEXT NOT NULL,
  badge_sekolah TEXT DEFAULT '-',
  badge_osis TEXT DEFAULT '-',
  dasi TEXT DEFAULT '-',
  ikat_pinggang TEXT DEFAULT '-',
  kaos_kaki TEXT DEFAULT '-',
  sepatu TEXT DEFAULT '-',
  atribut_lainnya TEXT DEFAULT '-',
  keterangan TEXT DEFAULT '-',
  status_hp TEXT DEFAULT 'HP Tidak Dikumpulkan',
  keterangan_hp TEXT DEFAULT '-',
  foto_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_absensi_harian UNIQUE (tanggal, id_siswa)
);

-- 6. Tabel PENGATURAN
CREATE TABLE IF NOT EXISTS public.pengaturan (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  keterangan TEXT DEFAULT ''
);

-- 7. Tabel JADWAL_PETUGAS
CREATE TABLE IF NOT EXISTS public.jadwal_petugas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hari TEXT NOT NULL,
  id_atau_username TEXT DEFAULT '',
  nama_petugas TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'Anggota OSIS',
  status TEXT NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Tabel PERSETUJUAN_ABSENSI
CREATE TABLE IF NOT EXISTS public.persetujuan_absensi (
  id_request TEXT PRIMARY KEY,
  waktu_request TEXT NOT NULL,
  pemohon TEXT NOT NULL,
  role TEXT NOT NULL,
  nama_siswa TEXT NOT NULL,
  kelas TEXT NOT NULL,
  data_absensi_json JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'Menunggu',
  diproses_oleh TEXT DEFAULT '-',
  alasan TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Tabel AUDIT_ABSENSI
CREATE TABLE IF NOT EXISTS public.audit_absensi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  waktu TIMESTAMPTZ DEFAULT NOW(),
  aksi TEXT NOT NULL,
  id_absensi TEXT NOT NULL,
  pelaku TEXT NOT NULL,
  detail TEXT DEFAULT ''
);

